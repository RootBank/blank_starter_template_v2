#!/usr/bin/env node
/**
 * Regenerate llms-full.txt at the repo root by concatenating CLAUDE.md, AGENTS.md,
 * every numbered doc, the glossary, the Stripe reference, the spec template, and
 * the provider-integration prompt. Each file is preceded by an anchor of the form
 * `## <basename-without-extension>` so an agent can cite individual sections.
 *
 * Modes:
 *   (default)   Write llms-full.txt.
 *               `npm run build:llms` (from collection_module/)
 *   --check     Regenerate in memory, compare against the committed llms-full.txt,
 *               and exit non-zero with a per-section diff summary on mismatch.
 *               Writes nothing. Used by CI to make the generated file unable to drift.
 *               `npm run build:llms:check` (from collection_module/)
 *
 * Output is deterministic — running twice produces zero diff.
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const DOCS = path.join(REPO_ROOT, 'collection_module', 'docs');
const OUT_PATH = path.join(REPO_ROOT, 'llms-full.txt');

const ORDER = [
  path.join(REPO_ROOT, 'CLAUDE.md'),
  path.join(REPO_ROOT, 'AGENTS.md'),
  path.join(DOCS, '00-OVERVIEW.md'),
  path.join(DOCS, '01-GETTING-STARTED.md'),
  path.join(DOCS, '02-ARCHITECTURE.md'),
  path.join(DOCS, '03-PROVIDER-INTERFACE.md'),
  path.join(DOCS, '04-CONTROLLERS.md'),
  path.join(DOCS, '05-CLIENTS.md'),
  path.join(DOCS, '06-ADAPTERS.md'),
  path.join(DOCS, '07-LIFECYCLE-HOOKS.md'),
  path.join(DOCS, '08-WEBHOOKS.md'),
  path.join(DOCS, '09-TESTING.md'),
  path.join(DOCS, '10-DEPLOYMENT.md'),
  path.join(DOCS, '11-CONFIGURATION.md'),
  path.join(DOCS, '12-ERROR-HANDLING.md'),
  path.join(DOCS, '13-BUILD-FROM-SPEC.md'),
  path.join(DOCS, '14-SELF-REVIEW.md'),
  path.join(DOCS, '15-PROVIDER-PATTERNS.md'),
  path.join(DOCS, '16-WHEN-TO-DEVIATE.md'),
  path.join(DOCS, '17-SCHEDULED-PAYMENTS.md'),
  path.join(DOCS, 'GLOSSARY.md'),
  path.join(DOCS, 'STRIPE-REFERENCE.md'),
  path.join(DOCS, 'SPEC-TEMPLATE.md'),
  path.join(DOCS, 'PROVIDER-INTEGRATION-PROMPT.md'),
];

const HEADER =
  '<!-- Generated by scripts/build-llms-full.js. Do not edit by hand. -->\n' +
  '<!-- To regenerate: `npm run build:llms` from collection_module/ -->\n\n';

const REGEN_HINT = 'Run `npm run build:llms` (from collection_module/) and commit the result.';

function bytes(text) {
  return Buffer.byteLength(text, 'utf8');
}

function anchor(filePath) {
  return path.basename(filePath, '.md');
}

/** Read every source doc. Exits 1 if any is missing. */
function readSections() {
  const missing = ORDER.filter((p) => !fs.existsSync(p));
  if (missing.length) {
    console.error('Missing input files:');
    for (const m of missing) console.error('  ' + path.relative(REPO_ROOT, m));
    process.exit(1);
  }
  return ORDER.map((file) => ({
    anchor: anchor(file),
    source: path.relative(REPO_ROOT, file),
    body: fs.readFileSync(file, 'utf8').replace(/\s+$/, ''),
  }));
}

function render(sections) {
  const parts = [HEADER];
  for (const s of sections) parts.push(`## ${s.anchor}\n\n${s.body}\n\n`);
  return parts.join('');
}

/**
 * Split committed output back into sections.
 *
 * Only a line that exactly matches the *next* expected anchor opens a section, so a
 * literal `## GLOSSARY` inside a doc body cannot be mistaken for a section boundary.
 * Anything before the first anchor is returned as `preamble` (normally HEADER).
 */
function parseSections(text, expectedAnchors) {
  const sections = new Map();
  const preamble = [];
  let next = 0;
  let current = null;

  for (const line of text.split('\n')) {
    if (next < expectedAnchors.length && line === `## ${expectedAnchors[next]}`) {
      current = { anchor: expectedAnchors[next], lines: [] };
      sections.set(current.anchor, current);
      next += 1;
      continue;
    }
    (current ? current.lines : preamble).push(line);
  }

  for (const section of sections.values()) {
    section.body = section.lines.join('\n').replace(/^\n+/, '').replace(/\s+$/, '');
  }

  return { preamble: preamble.join('\n'), sections };
}

function truncate(line) {
  const text = line === undefined ? '<end of section>' : line;
  return text.length > 100 ? `${text.slice(0, 100)}…` : text;
}

/** First positional line difference between two bodies, or null if identical. */
function firstLineDiff(expectedBody, actualBody) {
  if (expectedBody === actualBody) return null;
  const expected = expectedBody.split('\n');
  const actual = actualBody.split('\n');
  const limit = Math.max(expected.length, actual.length);
  for (let i = 0; i < limit; i += 1) {
    if (expected[i] !== actual[i]) {
      return { line: i + 1, expected: expected[i], actual: actual[i] };
    }
  }
  return { line: 1, expected: expected[0], actual: actual[0] };
}

function check(sections, expected) {
  if (!fs.existsSync(OUT_PATH)) {
    console.error(`llms-full.txt is missing at ${path.relative(REPO_ROOT, OUT_PATH)}.`);
    console.error(REGEN_HINT);
    return 1;
  }

  const actual = fs.readFileSync(OUT_PATH, 'utf8');
  if (actual === expected) {
    console.log(`llms-full.txt is up to date (${bytes(expected)} bytes, ${sections.length} sources).`);
    return 0;
  }

  console.error('llms-full.txt is out of date — it does not match the current docs.\n');
  const actualBytes = bytes(actual);
  const expectedBytes = bytes(expected);
  const delta = expectedBytes - actualBytes;
  console.error(
    `  committed: ${actualBytes} bytes` +
      `\n  generated: ${expectedBytes} bytes (${delta >= 0 ? '+' : ''}${delta})\n`
  );

  const parsed = parseSections(actual, sections.map((s) => s.anchor));

  if (parsed.preamble.replace(/\s+$/, '') !== HEADER.replace(/\s+$/, '')) {
    console.error('  [header]  generated banner differs or is missing');
  }

  let differing = 0;
  for (const section of sections) {
    const found = parsed.sections.get(section.anchor);
    if (!found) {
      differing += 1;
      console.error(`  [missing] ## ${section.anchor}  (from ${section.source})`);
      continue;
    }
    const diff = firstLineDiff(section.body, found.body);
    if (!diff) continue;
    differing += 1;
    console.error(`  [changed] ## ${section.anchor}  (from ${section.source}), first diff at section line ${diff.line}`);
    console.error(`              committed: ${truncate(diff.actual)}`);
    console.error(`              generated: ${truncate(diff.expected)}`);
  }

  if (differing === 0) {
    console.error('  Sections all match; the difference is in spacing or section ordering.');
  }

  console.error(`\n${REGEN_HINT}`);
  return 1;
}

function main() {
  const args = process.argv.slice(2);

  if (args.includes('--help') || args.includes('-h')) {
    console.log('Usage: node scripts/build-llms-full.js [--check]\n');
    console.log('  (no flags)  Regenerate and write llms-full.txt.');
    console.log('  --check     Compare the committed llms-full.txt against a fresh');
    console.log('              regeneration. Writes nothing; exits 1 on mismatch.');
    return 0;
  }

  const unknown = args.filter((a) => !['--check'].includes(a));
  if (unknown.length) {
    console.error(`Unknown argument(s): ${unknown.join(', ')}`);
    console.error('Usage: node scripts/build-llms-full.js [--check]');
    return 2;
  }

  const sections = readSections();
  const output = render(sections);

  if (args.includes('--check')) return check(sections, output);

  fs.writeFileSync(OUT_PATH, output);
  console.log(`wrote ${path.relative(REPO_ROOT, OUT_PATH)} (${bytes(output)} bytes, ${ORDER.length} sources)`);
  return 0;
}

process.exit(main());
